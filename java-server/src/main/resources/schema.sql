-- ============================================================
-- L7VP 达梦 DM8 数据库建表脚本 (v2.1)
-- Schema: DIG_GEO (替代旧 L7VP_PROJECTS)
-- 表数量: 9 张
--
-- 【本脚本是幂等的：可以反复执行，已有的一律不建、不改、不删】
--   · 模式不存在 → 建；已存在 → 跳过   (CREATE SCHEMA IF NOT EXISTS)
--   · 表不存在   → 建；已存在 → 跳过   (CREATE TABLE  IF NOT EXISTS)
--   · 索引不存在 → 建；已存在 → 跳过   (CREATE INDEX  IF NOT EXISTS)
--   · 唯一会被写数据的只有 TILE_CONFIG 的默认瓦片那一行，
--     且只在**缺行**时插入——已有配置（用户可能在页面里改过底图）不会被覆盖。
--
-- 【执行前想先看现状】先单独跑这一句，看 9 张表建了几张：
--   SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER = 'DIG_GEO' ORDER BY TABLE_NAME;
--   9 张都在 → 说明已经建过，本脚本跑下去不会产生任何改动（跑也无害）。
-- （有的达梦版本没有 ALL_TABLES，可换 DBA_TABLES，或看 SYSOBJECTS。）
--
-- 【执行方式】整个文件贴进达梦客户端（DM Manager / disql）执行即可。
--   脚本内表名全部带 DIG_GEO. 前缀，因此与当前连接所在的模式无关。
--   脚本最后一条是只读的核对查询，会把 9 张表的在位情况列出来。
--
-- 【万一客户端报语法错】只可能是 IF NOT EXISTS 不被你那个达梦版本接受
--   （本脚本用的写法与仓库里原来那份 v2.0 完全一致，线上库就是用它建的，正常不会报）。
--   处理办法：手工把模式建出来（CREATE SCHEMA DIG_GEO;），再把脚本里
--   CREATE … IF NOT EXISTS 的 IF NOT EXISTS 去掉，并只挑没建过的表执行。
-- ============================================================

-- 创建 Schema（没有才建）
CREATE SCHEMA IF NOT EXISTS DIG_GEO;

-- ============================================================
-- 1. PROJECTS — 项目主表
-- ============================================================
CREATE TABLE IF NOT EXISTS DIG_GEO.PROJECTS (
  PROJECT_ID        VARCHAR(50)  PRIMARY KEY,
  PROJECT_NAME      VARCHAR(200),
  DESCRIPTION       VARCHAR(500),
  CREATE_TIME       VARCHAR(50),
  UPDATE_TIME       VARCHAR(50),
  THUMBNAIL         VARCHAR(500),
  ASSET_PACKAGE_IDS VARCHAR(500),
  MAP_CONFIG        VARCHAR(4000)
);

CREATE INDEX IF NOT EXISTS IDX_PROJECTS_NAME       ON DIG_GEO.PROJECTS(PROJECT_NAME);
CREATE INDEX IF NOT EXISTS IDX_PROJECTS_CREATE_TIME ON DIG_GEO.PROJECTS(CREATE_TIME);

COMMENT ON TABLE DIG_GEO.PROJECTS IS '项目主表';
COMMENT ON COLUMN DIG_GEO.PROJECTS.PROJECT_ID IS '项目ID (UUID)';
COMMENT ON COLUMN DIG_GEO.PROJECTS.PROJECT_NAME IS '项目名称';
COMMENT ON COLUMN DIG_GEO.PROJECTS.DESCRIPTION IS '项目描述';
COMMENT ON COLUMN DIG_GEO.PROJECTS.CREATE_TIME IS '创建时间 (yyyy-MM-dd HH:mm:ss)';
COMMENT ON COLUMN DIG_GEO.PROJECTS.UPDATE_TIME IS '最后修改时间';
COMMENT ON COLUMN DIG_GEO.PROJECTS.THUMBNAIL IS '缩略图 URL';
COMMENT ON COLUMN DIG_GEO.PROJECTS.ASSET_PACKAGE_IDS IS '资产包ID列表 (JSON数组)';

-- ============================================================
-- 2. DATASETS — 数据集元数据表
-- ============================================================
CREATE TABLE IF NOT EXISTS DIG_GEO.DATASETS (
  DATASET_ID   VARCHAR(50)  PRIMARY KEY,
  PROJECT_ID   VARCHAR(50)  NOT NULL,
  DATASET_NAME VARCHAR(200),
