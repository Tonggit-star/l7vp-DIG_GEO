COMMENT ON COLUMN DIG_GEO.DATASETS.METADATA IS 'JSON, 数据集元信息 (columnsMeta, rowCount 等)';
COMMENT ON COLUMN DIG_GEO.DATASETS.FILTER IS 'JSON, 数据集筛选器配置 (relation, children 等)';
COMMENT ON COLUMN DIG_GEO.DATASETS.CREATE_TIME IS '创建时间';

