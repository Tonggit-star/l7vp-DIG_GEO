-- 7. TILE_CONFIG — 瓦片全局配置表 (单例)
-- ============================================================
CREATE TABLE IF NOT EXISTS DIG_GEO.TILE_CONFIG (
  ID          VARCHAR(10)  PRIMARY KEY,
  TILE_URL    VARCHAR(500),
  TILE_NAME   VARCHAR(100),
  MIN_ZOOM    INT,
  MAX_ZOOM    INT,
  UPDATE_TIME VARCHAR(50),
  IS_DEFAULT  VARCHAR(10),
  DEFAULT_NUM INT,
  CRS         VARCHAR(50),
  TILE_SCHEME VARCHAR(50),
  ORIGIN      VARCHAR(100)
);

COMMENT ON TABLE DIG_GEO.TILE_CONFIG IS '瓦片全局配置表 (仅1条记录)';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.ID IS '主键, 固定值 "default", 单例';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.TILE_URL IS 'XYZ瓦片地址模板 (含 {x} {y} {z} 占位符)';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.TILE_NAME IS '底图显示名称 (如 "内网卫星影像")';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.MIN_ZOOM IS '最小缩放级别, 默认0';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.MAX_ZOOM IS '最大缩放级别, 默认18';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.UPDATE_TIME IS '最后修改时间';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.IS_DEFAULT IS '是否默认瓦片: 1=是';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.DEFAULT_NUM IS '默认瓦片排序编号';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.CRS IS '坐标系类型: EPSG:3857 或 EPSG:4326';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.TILE_SCHEME IS '瓦片编号方式: XYZ 或 TMS';
COMMENT ON COLUMN DIG_GEO.TILE_CONFIG.ORIGIN IS '瓦片原点: lng,lat 格式';

-- 插入默认瓦片配置 (高德公开瓦片, 兜底)
-- 语义 = 「缺这一行才插」：底图地址可以在项目页「底图配置」里改并存回这张表，
-- 重跑本脚本**不会**把它冲回高德。
-- 用 INSERT … WHERE NOT EXISTS 而不是 MERGE：效果一样，但不依赖 MERGE 的单分支写法，
-- 任何达梦版本都不会有方言问题。
INSERT INTO DIG_GEO.TILE_CONFIG (ID, TILE_URL, TILE_NAME, MIN_ZOOM, MAX_ZOOM, UPDATE_TIME)
SELECT 'default',
       'https://webrd0{1-4}.is.autonavi.com/appmaptile?lang=zh_cn&size=1&scale=1&style=8&x={x}&y={y}&z={z}',
       '高德标准地图',
       0,
       18,
       TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS')
FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM DIG_GEO.TILE_CONFIG WHERE ID = 'default');

