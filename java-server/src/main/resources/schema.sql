CREATE INDEX IF NOT EXISTS IDX_DATASETS_PROJECT ON DIG_GEO.DATASETS(PROJECT_ID);

COMMENT ON TABLE DIG_GEO.DATASETS IS '数据集元数据表';
COMMENT ON COLUMN DIG_GEO.DATASETS.DATASET_ID IS '数据集ID (UUID)';
COMMENT ON COLUMN DIG_GEO.DATASETS.PROJECT_ID IS '所属项目ID';
COMMENT ON COLUMN DIG_GEO.DATASETS.DATASET_NAME IS '数据集名称';
